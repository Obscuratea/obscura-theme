#!/usr/bin/env python3
"""Generate the KDE color schemes (.colors) for Obscura Dark / Light."""
import sys, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).parent))
from palette import *

def T(x): return rgb(x) if isinstance(x, str) else tuple(x)

def c(t): return "%d,%d,%d" % T(t)

def group(name, v, bg, alt, accent):
    a = rgb(accent)
    ink = rgb(v["ink"]); bgc = T(bg); alt = T(alt)
    return f"""[Colors:{name}]
BackgroundAlternate={c(alt)}
BackgroundNormal={c(bgc)}
DecorationFocus={c(a)}
DecorationHover={c(a)}
ForegroundActive={c(a)}
ForegroundInactive={c(mix(bgc, ink, v['muted']))}
ForegroundLink={c(accent_ink(accent, v))}
ForegroundNegative={c(rgb(v['negative']))}
ForegroundNeutral={c(rgb(v['neutral']))}
ForegroundNormal={c(ink)}
ForegroundPositive={c(rgb(v['positive']))}
ForegroundVisited={c(rgb(v['visited']))}
"""

def build(v, accent=DEFAULT_ACCENT):
    a = rgb(accent); ink = rgb(v["ink"]); on = rgb(v["on_accent"])
    win = rgb(v["window"])
    out = ["# Obscura - generated by tools/gen_colors.py, do not edit by hand.\n"]
    out.append("""[ColorEffects:Disabled]
Color=%s
ColorAmount=0
ColorEffect=0
ContrastAmount=0.65
ContrastEffect=1
IntensityAmount=0.1
IntensityEffect=2

[ColorEffects:Inactive]
ChangeSelectionColor=true
Color=%s
ColorAmount=0.025
ColorEffect=2
ContrastAmount=0.1
ContrastEffect=2
Enable=false
IntensityAmount=0
IntensityEffect=0
""" % (c(mix(win, ink, 0.15)), c(mix(win, ink, 0.4))))
    out.append(group("Button", v, v["button"], rgb(v["window_alt"]), accent))
    out.append(group("Complementary", v, v["header"], rgb(v["window_alt"]), accent))
    out.append(group("Header", v, v["header"], rgb(v["window"]), accent))
    out.append(group("Header][Inactive", v, v["window"], rgb(v["header"]), accent))
    sel = group("Selection", v, hexs(a), hexs(mix(a, win, 0.5)), accent)
    sel = (sel.replace(f"ForegroundNormal={c(ink)}", f"ForegroundNormal={c(on)}")
              .replace(f"ForegroundActive={c(a)}", f"ForegroundActive={c(on)}")
              .replace(f"ForegroundLink={c(accent_ink(accent, v))}", f"ForegroundLink={c(on)}")
              .replace(f"ForegroundInactive={c(mix(a, ink, v['muted']))}", f"ForegroundInactive={c(mix(a, on, 0.4))}"))
    out.append(sel)
    out.append(group("Tooltip", v, v["tooltip"], rgb(v["window_alt"]), accent))
    out.append(group("View", v, v["view"], rgb(v["view_alt"]), accent))
    out.append(group("Window", v, v["window"], rgb(v["window_alt"]), accent))
    out.append(f"""[General]
ColorScheme={v['id']}
Name={v['name']}
shadeSortColumn=true

[KDE]
contrast=4

[WM]
activeBackground={c(rgb(v['titlebar_active']))}
activeBlend={c(ink)}
activeForeground={c(ink)}
inactiveBackground={c(rgb(v['titlebar_inactive']))}
inactiveBlend={c(mix(win, ink, v['muted']))}
inactiveForeground={c(mix(win, ink, v['muted']))}
""")
    return "\n".join(out)

if __name__ == "__main__":
    dest = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else "build/color-schemes")
    dest.mkdir(parents=True, exist_ok=True)
    for v in (DARK, LIGHT):
        (dest / f"{v['id']}.colors").write_text(build(v))
        print("wrote", dest / f"{v['id']}.colors")
